"""
pretrain_backbone_urban.py — Pre-train the MLP backbone on urban ray-tracing data.

Loads a dataset generated by generate_urban_dataset.py, fully unfreezes the
RadioMLPWithLoRA model, trains it with cosine-annealed AdamW, and saves the
best checkpoint as backbone_urban.pt.

Usage
-----
    python pretrain_backbone_urban.py \\
        --dataset    urban_dataset.npz \\
        --output     backbone_urban.pt \\
        --epochs     300              \\
        --lr         1e-3             \\
        --batch-size 4096

The saved checkpoint contains:
  model_state : dict   – state_dict compatible with RadioMLPWithLoRA
  input_dim   : int    – 8
  hidden_sizes: list   – e.g. [128, 128]
"""

import argparse
import sys
from pathlib import Path

import numpy as np
import torch
import torch.nn as nn
import torch.optim as optim

sys.path.insert(0, str(Path(__file__).parent))
from sionna_baseline.radio_mlp_lora import RadioMLPWithLoRA

HIDDEN_SIZES = (128, 128)
RANK         = 16
ALPHA        = 1.0


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser()
    p.add_argument("--dataset",     default="urban_etoile.npz")
    p.add_argument("--output",      default="backbone_etoile.pt")
    p.add_argument("--epochs",      type=int,   default=300)
    p.add_argument("--lr",          type=float, default=1e-3)
    p.add_argument("--batch-size",  type=int,   default=4096)
    p.add_argument("--val-frac",    type=float, default=0.1)
    p.add_argument("--seed",        type=int,   default=42)
    return p.parse_args()


def main() -> None:
    args = parse_args()
    torch.manual_seed(args.seed)
    np.random.seed(args.seed)

    # ── load dataset ──────────────────────────────────────────────────────────
    data = np.load(args.dataset)
    X_np = data["features"].astype(np.float32)   # (N, 8) – already encoder-normalised
    Y_np = data["targets"].astype(np.float32)    # (N,)   – RSSI in dBm
    print(f"Dataset: {len(X_np):,} samples  "
          f"RSSI [{Y_np.min():.1f}, {Y_np.max():.1f}] dBm")

    # ── train / validation split ──────────────────────────────────────────────
    n_val = max(1, int(len(X_np) * args.val_frac))
    idx   = np.random.permutation(len(X_np))
    val_idx, tr_idx = idx[:n_val], idx[n_val:]

    X_tr  = torch.from_numpy(X_np[tr_idx]);   Y_tr  = torch.from_numpy(Y_np[tr_idx])
    X_val = torch.from_numpy(X_np[val_idx]);  Y_val = torch.from_numpy(Y_np[val_idx])
    print(f"Train: {len(X_tr):,}  Val: {len(X_val):,}", flush=True)

    # ── model — fully unfrozen for pretraining ────────────────────────────────
    model = RadioMLPWithLoRA(
        input_dim=8, hidden_sizes=HIDDEN_SIZES,
        rank=RANK, alpha=ALPHA,
        fspl_const=None,   # no physics prior — data-driven urban backbone
    )
    model._unfreeze_all()
    n_params = sum(p.numel() for p in model.parameters())
    print(f"Model parameters: {n_params:,}", flush=True)

    # ── optimiser + schedule ──────────────────────────────────────────────────
    optimizer = optim.AdamW(model.parameters(), lr=args.lr, weight_decay=1e-4)
    scheduler = optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=args.epochs)
    loss_fn   = nn.HuberLoss(delta=5.0)   # robust to deep-fade outliers

    best_val_loss = float("inf")
    best_state: dict | None = None

    # ── training loop ─────────────────────────────────────────────────────────
    for epoch in range(1, args.epochs + 1):
        model.train()
        perm = torch.randperm(len(X_tr))
        tr_loss, nb = 0.0, 0
        for start in range(0, len(X_tr), args.batch_size):
            xb = X_tr[perm[start : start + args.batch_size]]
            yb = Y_tr[perm[start : start + args.batch_size]]
            optimizer.zero_grad()
            loss = loss_fn(model(xb), yb)
            loss.backward()
            optimizer.step()
            tr_loss += float(loss.item()); nb += 1
        scheduler.step()

        model.eval()
        with torch.no_grad():
            val_pred = model(X_val)
            val_loss = float(loss_fn(val_pred, Y_val).item())
            val_rmse = float(torch.sqrt(torch.mean((val_pred - Y_val) ** 2)).item())

        if val_loss < best_val_loss:
            best_val_loss = val_loss
            best_state    = {k: v.detach().cpu().clone()
                             for k, v in model.state_dict().items()}

        if epoch % 50 == 0 or epoch == 1:
            print(f"  epoch {epoch:4d}/{args.epochs}  "
                  f"tr_loss={tr_loss/nb:.4f}  "
                  f"val_loss={val_loss:.4f}  val_rmse={val_rmse:.2f} dB  "
                  f"lr={scheduler.get_last_lr()[0]:.2e}", flush=True)

    # ── save best checkpoint ──────────────────────────────────────────────────
    assert best_state is not None
    torch.save(
        {
            "model_state":  best_state,
            "input_dim":    8,
            "hidden_sizes": list(HIDDEN_SIZES),
        },
        args.output,
    )
    print(f"\nSaved backbone → {args.output}  "
          f"(best val_loss={best_val_loss:.4f})")


if __name__ == "__main__":
    main()
